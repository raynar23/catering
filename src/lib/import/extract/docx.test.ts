// Unit tests for docx extractor
import { describe, it, expect, vi } from "vitest";
import { DocxExtractor } from "./docx";
import mammoth from "mammoth";

vi.mock("mammoth", () => ({
  default: {
    convertToHtml: vi.fn(),
  },
}));

describe("extract/docx.ts", () => {
  it("extracts tables from html generated by mammoth", async () => {
    const mockHtml = `
      <table>
        <tr><th>No</th><th>Tanggal</th><th>Shift</th><th>Vendor</th></tr>
        <tr><td>1</td><td>2026-10-01</td><td>Siang</td><td>Aisya Catering</td></tr>
        <tr><td>2</td><td>2026-10-01</td><td>Sore</td><td>Catering IBU</td></tr>
      </table>
    `;

    vi.mocked(mammoth.convertToHtml).mockResolvedValueOnce({
      value: mockHtml,
      messages: [],
    });

    const extractor = new DocxExtractor();
    const tables = await extractor.extract(Buffer.from("dummy"), "test.docx");

    expect(tables.length).toBe(1);
    expect(tables[0].headers).toEqual(["No", "Tanggal", "Shift", "Vendor"]);
    expect(tables[0].rows.length).toBe(2);
    expect(tables[0].rows[0]).toEqual(["1", "2026-10-01", "Siang", "Aisya Catering"]);
  });

  it("extracts paragraphs if document contains no tables", async () => {
    const mockHtml = `
      <p>Baris 1 Dokumen</p>
      <p>Baris 2 Dokumen</p>
    `;

    vi.mocked(mammoth.convertToHtml).mockResolvedValueOnce({
      value: mockHtml,
      messages: [],
    });

    const extractor = new DocxExtractor();
    const tables = await extractor.extract(Buffer.from("dummy"), "test.docx");

    expect(tables.length).toBe(1);
    expect(tables[0].headers).toEqual(["Teks"]);
    expect(tables[0].rows).toEqual([["Baris 1 Dokumen"], ["Baris 2 Dokumen"]]);
  });
});
